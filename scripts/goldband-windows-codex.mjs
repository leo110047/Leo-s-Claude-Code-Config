import fs from 'node:fs';
import path from 'node:path';
import {
  backupExistingPath,
  colorize,
  ensureComponent,
  ensureDir,
  ensureManagedLink,
  fileContentsMatch,
  isRepoSymlink,
  isSamePath,
  lstatOrNull,
  removePath,
  updateWindowsState,
} from './goldband-windows-core.mjs';

function isGeneratedCodexConfig(targetPath) {
  if (!fs.existsSync(targetPath)) {
    return false;
  }
  const firstLine = fs.readFileSync(targetPath, 'utf8').split(/\r?\n/, 1)[0];
  return firstLine === '# Generated by goldband Codex config installer';
}

function splitTomlSections(contents) {
  const lines = contents.split(/\r?\n/);
  const firstTableIndex = lines.findIndex((line) => /^\s*\[/.test(line));
  if (firstTableIndex === -1) {
    return {
      root: contents.trimEnd(),
      tables: '',
    };
  }

  return {
    root: lines.slice(0, firstTableIndex).join('\n').trimEnd(),
    tables: lines.slice(firstTableIndex).join('\n').trimEnd(),
  };
}

function writeGeneratedCodexConfig(context) {
  const baseConfig = path.join(context.repoDir, 'codex', 'config.toml');
  const localConfig = path.join(
    context.repoDir,
    'codex',
    'local',
    'config.toml',
  );
  const destPath = context.paths.codexConfigFile;

  if (!fs.existsSync(baseConfig)) {
    console.log(
      `  ${colorize(context.colorsEnabled, 'yellow', '[skip]')} Codex config.toml — source missing`,
    );
    return;
  }

  const stat = lstatOrNull(destPath);
  if (stat) {
    if (stat.isSymbolicLink() || isGeneratedCodexConfig(destPath)) {
      removePath(destPath);
    } else {
      backupExistingPath(destPath, context);
    }
  }

  const baseSections = splitTomlSections(fs.readFileSync(baseConfig, 'utf8'));
  const localSections = fs.existsSync(localConfig)
    ? splitTomlSections(fs.readFileSync(localConfig, 'utf8'))
    : null;

  const lines = [
    '# Generated by goldband Codex config installer',
    `# Source: ${baseConfig}`,
    fs.existsSync(localConfig)
      ? `# Local overlay: ${localConfig}`
      : '# Local overlay: none',
    '',
    '# --- goldband portable root keys ---',
    baseSections.root,
  ];

  if (localSections) {
    lines.push('', '# --- goldband local root keys ---', localSections.root);
  }

  lines.push('', '# --- goldband portable tables ---', baseSections.tables);

  if (localSections) {
    lines.push('', '# --- goldband local tables ---', localSections.tables);
  }

  ensureDir(path.dirname(destPath));
  fs.writeFileSync(destPath, `${lines.join('\n')}\n`, 'utf8');
  const suffix = fs.existsSync(localConfig)
    ? 'base + local overlay'
    : 'base only';
  console.log(
    `  ${colorize(context.colorsEnabled, 'green', '[install]')} Codex config.toml (${suffix})`,
  );
}

function installCodexProfileConfigs(context) {
  const sourceDir = path.join(context.repoDir, 'codex', 'profiles');
  if (!fs.existsSync(sourceDir)) {
    console.log(
      `  ${colorize(context.colorsEnabled, 'yellow', '[skip]')} Codex profile configs — source missing`,
    );
    return;
  }

  for (const entry of fs
    .readdirSync(sourceDir)
    .filter((name) => name.endsWith('.config.toml'))
    .sort()) {
    ensureComponent(
      context,
      path.join(sourceDir, entry),
      path.join(context.paths.codexDir, entry),
      `Codex profile ${entry}`,
      'file',
    );
  }
}

function installCodexRequirements(context) {
  ensureComponent(
    context,
    path.join(context.repoDir, 'codex', 'requirements.toml'),
    context.paths.codexRequirementsFile,
    'Codex requirements template (Windows enforcement path unverified)',
    'file',
  );
  updateWindowsState(context, (state) => {
    state.codexComponents.requirements = true;
  });
}

function removeCodexRequirements(context) {
  const sourcePath = path.join(context.repoDir, 'codex', 'requirements.toml');
  const targetPath = context.paths.codexRequirementsFile;
  if (!fs.existsSync(targetPath)) {
    return;
  }
  if (
    fs.existsSync(sourcePath) &&
    fs.readFileSync(sourcePath, 'utf8') === fs.readFileSync(targetPath, 'utf8')
  ) {
    removePath(targetPath);
  }
}

function removeManagedClaudeGuidance(context, state) {
  const sourcePath = path.join(context.repoDir, 'claude', 'CLAUDE.md');
  const targetPath = context.paths.claudeGlobalInstructionsFile;
  if (!fs.existsSync(targetPath)) {
    return;
  }

  if (isRepoSymlink(targetPath, sourcePath)) {
    removePath(targetPath);
    return;
  }

  if (
    state.claudeComponents.guidance &&
    fileContentsMatch(sourcePath, targetPath)
  ) {
    removePath(targetPath);
    return;
  }

  console.log(
    `  ${colorize(context.colorsEnabled, 'yellow', '[preserve]')} Claude CLAUDE.md is not a goldband-managed file`,
  );
}

function isRepoCodexRuleLink(context, linkPath) {
  const stat = lstatOrNull(linkPath);
  if (!stat?.isSymbolicLink()) {
    return false;
  }
  const target = path.resolve(
    path.dirname(linkPath),
    fs.readlinkSync(linkPath),
  );
  const baseRules = path.join(context.repoDir, 'codex', 'rules');
  const localRules = path.join(context.repoDir, 'codex', 'local', 'rules');
  return (
    target.startsWith(`${baseRules}${path.sep}`) ||
    target.startsWith(`${localRules}${path.sep}`)
  );
}

function installCodexRuleFile(context, sourcePath, destPath, label) {
  const stat = lstatOrNull(destPath);
  if (stat) {
    if (stat.isSymbolicLink()) {
      const currentTarget = path.resolve(
        path.dirname(destPath),
        fs.readlinkSync(destPath),
      );
      if (isSamePath(currentTarget, sourcePath)) {
        console.log(
          `  ${colorize(context.colorsEnabled, 'green', '[ok]')} ${label}`,
        );
        return;
      }
      if (isRepoCodexRuleLink(context, destPath)) {
        removePath(destPath);
      } else {
        backupExistingPath(destPath, context);
      }
    } else {
      backupExistingPath(destPath, context);
    }
  }

  ensureManagedLink(context, sourcePath, destPath, 'file');
  console.log(
    `  ${colorize(context.colorsEnabled, 'green', '[install]')} ${label}`,
  );
}

function ensureCodexLocalDefaultRules(context) {
  const localDefault = path.join(
    context.repoDir,
    'codex',
    'local',
    'rules',
    'default.rules',
  );
  if (fs.existsSync(localDefault)) {
    return;
  }

  ensureDir(path.dirname(localDefault));
  fs.writeFileSync(
    localDefault,
    [
      '# Machine-local Codex execpolicy rules.',
      '# This ignored file is the writable default target for one-off approvals.',
      '',
    ].join('\n'),
    'utf8',
  );
}

function installCodexRulesDirectory(context) {
  const baseRules = path.join(context.repoDir, 'codex', 'rules');
  const localRules = path.join(context.repoDir, 'codex', 'local', 'rules');
  const destDir = context.paths.codexRulesDir;

  if (!fs.existsSync(baseRules)) {
    console.log(
      `  ${colorize(context.colorsEnabled, 'yellow', '[skip]')} Codex Rules — source missing`,
    );
    return;
  }

  const stat = lstatOrNull(destDir);
  if (stat?.isSymbolicLink() || (stat && !stat.isDirectory())) {
    removePath(destDir);
  }
  ensureDir(destDir);
  ensureCodexLocalDefaultRules(context);

  for (const entry of fs
    .readdirSync(baseRules)
    .filter((name) => name.endsWith('.rules'))
    .sort()) {
    const sourcePath = path.join(baseRules, entry);
    const destName = entry === 'default.rules' ? 'goldband.rules' : entry;
    installCodexRuleFile(
      context,
      sourcePath,
      path.join(destDir, destName),
      `Codex rule ${destName}`,
    );
  }

  if (!fs.existsSync(localRules)) {
    return;
  }

  for (const entry of fs
    .readdirSync(localRules)
    .filter((name) => name.endsWith('.rules'))
    .sort()) {
    const sourcePath = path.join(localRules, entry);
    installCodexRuleFile(
      context,
      sourcePath,
      path.join(destDir, entry),
      `Codex local rule ${entry}`,
    );
  }
}

export {
  installCodexProfileConfigs,
  installCodexRequirements,
  installCodexRulesDirectory,
  removeCodexRequirements,
  removeManagedClaudeGuidance,
  writeGeneratedCodexConfig,
};
