# This file must be sourced by bash, not executed directly.

is_generated_codex_config() {
    local path="$1"
    [ -f "$path" ] || return 1
    head -n 1 "$path" 2>/dev/null | grep -q '^# Generated by goldband Codex config installer$'
}

emit_toml_root_keys() {
    local path="$1"
    awk '
        /^[[:space:]]*\[/ { in_tables = 1 }
        !in_tables { print }
    ' "$path"
}

emit_toml_tables() {
    local path="$1"
    awk '
        /^[[:space:]]*\[/ { in_tables = 1 }
        in_tables { print }
    ' "$path"
}

install_generated_codex_config() {
    local base_config="$REPO_DIR/codex/config.toml"
    local local_config="$REPO_DIR/codex/local/config.toml"
    local dest="$CODEX_CONFIG_FILE"

    if [ ! -f "$base_config" ]; then
        echo -e "  ${YELLOW}[跳過] Codex config.toml — 來源不存在${NC}"
        return
    fi

    if [ -L "$dest" ]; then
        rm "$dest"
    elif [ -e "$dest" ] && ! is_generated_codex_config "$dest"; then
        backup_existing_path "$dest"
    fi

    mkdir -p "$(dirname "$dest")"

    local tmp="${dest}.tmp.$$"
    write_generated_codex_config "$base_config" "$local_config" > "$tmp"

    mv "$tmp" "$dest"

    if [ -f "$local_config" ]; then
        echo -e "  ${GREEN}[安裝] Codex config.toml (base + local overlay)${NC}"
    else
        echo -e "  ${GREEN}[安裝] Codex config.toml (base only)${NC}"
    fi
}

write_generated_codex_config() {
    local base_config="$1"
    local local_config="$2"

    echo "# Generated by goldband Codex config installer"
    echo "# Source: $base_config"
    if [ -f "$local_config" ]; then
        echo "# Local overlay: $local_config"
    else
        echo "# Local overlay: none"
    fi
    echo ""
    echo "# --- goldband portable root keys ---"
    emit_toml_root_keys "$base_config"
    emit_local_codex_config_section "$local_config" "root keys" emit_toml_root_keys
    echo ""
    echo "# --- goldband portable tables ---"
    emit_toml_tables "$base_config"
    emit_local_codex_config_section "$local_config" "tables" emit_toml_tables
}

emit_local_codex_config_section() {
    local local_config="$1"
    local label="$2"
    local emitter="$3"
    [ -f "$local_config" ] || return 0
    echo ""
    echo "# --- goldband local $label ---"
    "$emitter" "$local_config"
}

install_codex_profile_configs() {
    local profile_dir="$REPO_DIR/codex/profiles"

    if [ ! -d "$profile_dir" ]; then
        echo -e "  ${YELLOW}[跳過] Codex profile configs — 來源不存在${NC}"
        return
    fi

    local profile_file
    for profile_file in "$profile_dir"/*.config.toml; do
        [ -f "$profile_file" ] || continue
        link_component "$profile_file" "$CODEX_DIR/$(basename "$profile_file")" "Codex profile $(basename "$profile_file")"
    done
}

install_codex_requirements_file() {
    local src="$REPO_DIR/codex/requirements.toml"
    local dest="$CODEX_REQUIREMENTS_FILE"

    if [ ! -f "$src" ]; then
        echo -e "  ${YELLOW}[跳過] Codex requirements.toml — 來源不存在${NC}"
        return
    fi

    local dest_dir
    dest_dir="$(dirname "$dest")"
    local backup_suffix
    backup_suffix="$(date +%s)"

    local can_write_without_sudo=false
    if [ "$(id -u)" -eq 0 ]; then
        can_write_without_sudo=true
    elif mkdir -p "$dest_dir" 2>/dev/null && [ -w "$dest_dir" ]; then
        can_write_without_sudo=true
    fi

    if $can_write_without_sudo; then
        mkdir -p "$dest_dir"
        if [ -e "$dest" ] && ! cmp -s "$src" "$dest"; then
            cp "$dest" "${dest}.bak.${backup_suffix}"
            echo -e "  ${YELLOW}[備份] Codex requirements.toml -> ${dest}.bak.${backup_suffix}${NC}"
        fi
        cp "$src" "$dest"
        chmod 0644 "$dest"
    else
        sudo mkdir -p "$dest_dir"
        if sudo test -e "$dest" && ! sudo cmp -s "$src" "$dest"; then
            sudo cp "$dest" "${dest}.bak.${backup_suffix}"
            echo -e "  ${YELLOW}[備份] Codex requirements.toml -> ${dest}.bak.${backup_suffix}${NC}"
        fi
        sudo cp "$src" "$dest"
        sudo chmod 0644 "$dest"
    fi

    echo -e "  ${GREEN}[安裝] Codex managed requirements -> $dest${NC}"
}

is_repo_codex_rule_link() {
    local link_path="$1"
    local base_rules="$REPO_DIR/codex/rules"
    local local_rules="$REPO_DIR/codex/local/rules"

    [ -L "$link_path" ] || return 1

    local target
    target=$(readlink "$link_path")
    case "$target" in
        "$base_rules"/*|"$local_rules"/*)
            return 0
            ;;
        *)
            return 1
            ;;
    esac
}

link_codex_rule_file() {
    local src="$1"
    local dest="$2"
    local label="$3"

    if [ -L "$dest" ]; then
        local current_target
        current_target=$(readlink "$dest")
        if [ "$current_target" = "$src" ]; then
            echo -e "  ${GREEN}[已安裝] $label${NC}"
            return
        fi

        if is_repo_codex_rule_link "$dest"; then
            rm "$dest"
        else
            backup_existing_path "$dest"
        fi
    elif [ -e "$dest" ]; then
        echo -e "  ${YELLOW}[保留] $label — 目標已有非 goldband 檔案: $dest${NC}"
        return
    fi

    ln -s "$src" "$dest"
    echo -e "  ${GREEN}[安裝 (repo-linked)] $label${NC}"
}

ensure_codex_local_default_rules() {
    local local_default="$REPO_DIR/codex/local/rules/default.rules"

    if [ -f "$local_default" ]; then
        return
    fi

    mkdir -p "$(dirname "$local_default")"
    {
        echo "# Machine-local Codex execpolicy rules."
        echo "# This ignored file is the writable default target for one-off approvals."
        echo ""
    } > "$local_default"
}

prune_stale_codex_rule_links() {
    local entry
    for entry in "$CODEX_RULES_DIR"/*.rules; do
        if [ ! -e "$entry" ] && [ ! -L "$entry" ]; then
            continue
        fi
        if is_repo_codex_rule_link "$entry"; then
            local target
            target=$(readlink "$entry")
            if [ ! -e "$target" ]; then
                rm "$entry"
            fi
        fi
    done
}

install_codex_rules_dir() {
    local base_rules="$REPO_DIR/codex/rules"
    local local_rules="$REPO_DIR/codex/local/rules"

    if [ ! -d "$base_rules" ]; then
        echo -e "  ${YELLOW}[跳過] Codex Rules — 來源不存在${NC}"
        return
    fi

    if [ -L "$CODEX_RULES_DIR" ]; then
        rm "$CODEX_RULES_DIR"
    elif [ -e "$CODEX_RULES_DIR" ] && [ ! -d "$CODEX_RULES_DIR" ]; then
        backup_existing_path "$CODEX_RULES_DIR"
    fi

    mkdir -p "$CODEX_RULES_DIR"
    ensure_codex_local_default_rules
    prune_stale_codex_rule_links

    local rule_file
    for rule_file in "$base_rules"/*.rules; do
        [ -f "$rule_file" ] || continue
        local dest_name
        dest_name="$(basename "$rule_file")"
        if [ "$dest_name" = "default.rules" ]; then
            dest_name="goldband.rules"
        fi
        link_codex_rule_file "$rule_file" "$CODEX_RULES_DIR/$dest_name" "Codex rule $dest_name"
    done

    if [ -d "$local_rules" ]; then
        for rule_file in "$local_rules"/*.rules; do
            [ -f "$rule_file" ] || continue
            link_codex_rule_file "$rule_file" "$CODEX_RULES_DIR/$(basename "$rule_file")" "Codex local rule $(basename "$rule_file")"
        done
    fi
}

codex_portable_rules_have_local_state() {
    local base_rules="$REPO_DIR/codex/rules"
    [ -d "$base_rules" ] || return 1
    grep -R -q -F '/Users/' "$base_rules" ||
        grep -R -q -F '/private/tmp' "$base_rules" ||
        grep -R -q -F '.studio_os_write_token' "$base_rules" ||
        grep -R -q -F 'LaunchAgents' "$base_rules"
}

warn_codex_portable_rules_local_state() {
    if ! codex_portable_rules_have_local_state; then
        return 0
    fi

    echo -e "  ${YELLOW}[警告] Codex portable rules 含有本機 approvals，會阻止 self-update${NC}"
    echo -e "  ${CYAN}  建議執行:${NC} ./install.sh repair-codex-rules"
    echo -e "  ${CYAN}  這會把本機 approvals 從 codex/rules/default.rules 移到 ignored overlay:${NC}"
    echo -e "  ${CYAN}  codex/local/rules/default.rules${NC}"
}

repair_codex_local_rules() {
    local migrator="$REPO_DIR/scripts/migrate-codex-local-rules.py"
    local base_rules="$REPO_DIR/codex/rules/default.rules"
    local local_rules="$REPO_DIR/codex/local/rules/default.rules"

    if [ ! -f "$migrator" ]; then
        echo -e "  ${RED}[錯誤] 找不到 repair script: $migrator${NC}"
        return 1
    fi
    if ! command -v python3 >/dev/null 2>&1; then
        echo -e "  ${RED}[錯誤] repair-codex-rules 需要 python3${NC}"
        return 1
    fi

    python3 "$migrator" --base-rules "$base_rules" --local-rules "$local_rules"
    bash "$REPO_DIR/scripts/check-codex-portability.sh"
    install_codex_rules_dir
}
